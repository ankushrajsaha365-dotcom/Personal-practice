package Java.Java_new;

public class Operator3 {
    public static void main(String[] args) {
        int marks = 75;

        if (marks >= 40 && marks <= 100) {
            System.out.println("Pass");
        }

        if (marks < 40 || marks > 100) {
            System.out.println("Fail or Invalid");
        }
    }
    
}
